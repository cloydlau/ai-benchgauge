import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const catalog = JSON.parse(readFileSync(new URL('fc/purchase-links.json', root)))
const quoted = JSON.stringify
const links = choices => `[${(choices || []).map(({ label, url, site }) => {
  const parsed = new URL(url)
  if (parsed.protocol !== 'https:' || !parsed.hostname || parsed.username || parsed.password || /\s/.test(url)
    || !['mainlandChina', 'international', 'universal'].includes(site)) throw Error(`Invalid purchase link: ${url}`)
  return `PurchaseLink(label: ${quoted(label)}, url: try! PurchaseLinkCatalog.validatedURL(${quoted(url)}), site: .${site})`
}).join(', ')}]`
const source = `// Generated by Scripts/generate-purchase-links.mjs; edit fc/purchase-links.json instead.
import Foundation

enum PurchaseLinkData {
    private static let aliasesStorage: [String: String] = [
${Object.entries(catalog.aliases).map(([key, value]) => `        ${quoted(key)}: ${quoted(value)},`).join('\n')}
    ]
    static var aliases: [String: String] { aliasesStorage }
    private static let vendorsStorage: [String: [String: PurchaseLinks]] = [
${Object.entries(catalog.vendors).map(([key, variants]) => `        ${quoted(key)}: [
${Object.entries(variants).map(([category, value]) => `            ${quoted(category)}: PurchaseLinks(codingPlan: ${links(value.codingPlan)}, payAsYouGo: ${links(value.payAsYouGo)}),`).join('\n')}
        ],`).join('\n')}
    ]
    static var vendors: [String: [String: PurchaseLinks]] { vendorsStorage }
}
`
const output = new URL('Sources/LeaderboardKit/PurchaseLinkData.generated.swift', root)
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== source) throw Error('Purchase links are stale: run node Scripts/generate-purchase-links.mjs')
} else writeFileSync(output, source)
