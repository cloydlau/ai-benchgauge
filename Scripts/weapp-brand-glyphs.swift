// Export the native title fonts as offline outlines. The mini-program's views
// and Canvas exports consume the same geometry without loading a network font.
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let fontURL = root.appending(path: "Sources/LeaderboardKit/Resources/Fonts/BenchGaugeCalligraphy.ttf")
precondition(CTFontManagerRegisterFontsForURL(fontURL as CFURL, .process, nil))
let system = CTFontCreateUIFontForLanguage(.system, 21, nil)!
let traits = CTFontDescriptorCreateWithAttributes([kCTFontTraitsAttribute: [kCTFontWeightTrait: 0.3]] as CFDictionary)
let latin = CTFontCreateCopyWithAttributes(system, 21, nil, traits)
let chinese = CTFontCreateWithName("BenchGaugeCalligraphy-Regular" as CFString, 25, nil)
let english = CTFontCreateWithName("SnellRoundhand-Bold" as CFString, 21, nil)
precondition(CTFontCopyPostScriptName(chinese) as String == "BenchGaugeCalligraphy-Regular")
precondition(CTFontCopyPostScriptName(english) as String == "SnellRoundhand-Bold")

func outline(_ text: String, _ font: CTFont) -> CGPath {
    let line = CTLineCreateWithAttributedString(NSAttributedString(string: text,
        attributes: [NSAttributedString.Key(kCTFontAttributeName as String): font]))
    let result = CGMutablePath()
    for run in CTLineGetGlyphRuns(line) as! [CTRun] {
        let count = CTRunGetGlyphCount(run)
        var glyphs = [CGGlyph](repeating: 0, count: count), positions = [CGPoint](repeating: .zero, count: count)
        CTRunGetGlyphs(run, CFRange(), &glyphs)
        CTRunGetPositions(run, CFRange(), &positions)
        for index in 0..<count {
            guard let path = CTFontCreatePathForGlyph(font, glyphs[index], nil) else { preconditionFailure("Missing title glyph") }
            result.addPath(path, transform: CGAffineTransform(translationX: positions[index].x, y: positions[index].y))
        }
    }
    return result
}
func rounded(_ value: CGFloat) -> Double { (Double(value) * 10000).rounded() / 10000 }
var glyphs: [String: Any] = [:]
let directory = root.appending(path: "apps/weapp/assets/brand-glyphs")
try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
for (key, text, font) in [("zh-I", "I", latin), ("zh-tian", "天", chinese), ("zh-ti", "梯", chinese),
                           ("en-I", "I", english), ("en-name", "BenchGauge", english)] {
    let path = outline(text, font), bounds = path.boundingBoxOfPath
    var transform = CGAffineTransform(a: 1, b: 0, c: 0, d: -1, tx: -bounds.minX, ty: bounds.maxY)
    var commands: [[Any]] = []
    path.copy(using: &transform)!.applyWithBlock { pointer in
        let element = pointer.pointee
        let command: String, count: Int
        switch element.type {
        case .moveToPoint: (command, count) = ("M", 1)
        case .addLineToPoint: (command, count) = ("L", 1)
        case .addQuadCurveToPoint: (command, count) = ("Q", 2)
        case .addCurveToPoint: (command, count) = ("C", 3)
        case .closeSubpath: (command, count) = ("Z", 0)
        @unknown default: preconditionFailure("Unknown path element")
        }
        commands.append([command] + (0..<count).flatMap { [rounded(element.points[$0].x), rounded(element.points[$0].y)] })
    }
    let width = rounded(bounds.width), height = rounded(bounds.height)
    glyphs[key] = ["text": text, "width": width, "height": height, "commands": commands,
                   "font": CTFontCopyPostScriptName(font) as String]
    let d = commands.map { $0.map { String(describing: $0) }.joined(separator: " ") }.joined(separator: " ")
    let palettes: [(String, [(Double, String)])] = [
        ("", [(0, "#303945"), (0.42, "#8894A2"), (0.5, "#414D5C"), (1, "#6C7888")]),
        ("-dark", [(0, "#F5F7FA"), (0.42, "#A5AFBC"), (0.5, "#E0E6EE"), (1, "#8D99A8")]),
    ]
    for (suffix, stops) in palettes {
        let colors = stops.map { "<stop offset=\"\($0.0)\" stop-color=\"\($0.1)\"/>" }.joined()
        let gradient = "<linearGradient id=\"brand\" x1=\"0\" y1=\"0\" x2=\"0\" y2=\"\(height)\" gradientUnits=\"userSpaceOnUse\">\(colors)</linearGradient>"
        let svg = "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 \(width) \(height)\"><defs>\(gradient)</defs><path fill=\"url(#brand)\" d=\"\(d)\"/></svg>\n"
        try svg.write(to: directory.appending(path: "\(key)\(suffix).svg"), atomically: true, encoding: .utf8)
    }
}
let data = try JSONSerialization.data(withJSONObject: glyphs, options: [.sortedKeys])
let source = "// Generated by Scripts/weapp-brand-glyphs.swift from the native iOS title fonts.\nexport const brandGlyphs = \(String(decoding: data, as: UTF8.self))\n"
try source.write(to: root.appending(path: "apps/weapp/src/core/brand-glyphs.js"), atomically: true, encoding: .utf8)
print("Generated \(glyphs.count) native title glyph outlines and light/dark SVGs.")
